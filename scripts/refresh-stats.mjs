#!/usr/bin/env node
/**
 * Regenerates src/data/github-stats.ts from the GitHub APIs.
 *
 * Every number on the GitHub section of the page comes from here, so it is
 * reproducible rather than typed. Run it with either:
 *   gh auth login            (preferred — uses the gh CLI)
 *   GITHUB_TOKEN=ghp_...     (any token with public read scope)
 *
 *   npm run refresh:stats
 */
import { execFileSync } from "node:child_process";
import { writeFileSync, mkdtempSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

const USER = process.env.GH_USER ?? "utkarshsingx";
const to = new Date();
const from = new Date(Date.UTC(to.getUTCFullYear() - 1, to.getUTCMonth(), to.getUTCDate() + 1));

const QUERY = `query($u:String!,$f:DateTime!,$t:DateTime!){
  user(login:$u){
    contributionsCollection(from:$f,to:$t){
      totalCommitContributions
      restrictedContributionsCount
      totalPullRequestContributions
      totalPullRequestReviewContributions
      contributionCalendar{
        totalContributions
        weeks{ firstDay contributionDays{ date contributionCount } }
      }
    }
  }
}`;

async function graphql() {
  const variables = { u: USER, f: from.toISOString(), t: to.toISOString() };
  const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;
  if (token) {
    const res = await fetch("https://api.github.com/graphql", {
      method: "POST",
      headers: { authorization: `bearer ${token}`, "content-type": "application/json" },
      body: JSON.stringify({ query: QUERY, variables }),
    });
    if (!res.ok) throw new Error(`GraphQL ${res.status}: ${await res.text()}`);
    return (await res.json()).data;
  }
  // Fall back to the gh CLI. --input avoids shell-quoting the query.
  const file = join(mkdtempSync(join(tmpdir(), "ghstats-")), "q.json");
  writeFileSync(file, JSON.stringify({ query: QUERY, variables }));
  const out = execFileSync("gh", ["api", "graphql", "--input", file], { encoding: "utf8" });
  return JSON.parse(out).data;
}

async function rest(path) {
  const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;
  if (token) {
    const res = await fetch(`https://api.github.com/${path}`, {
      headers: { authorization: `bearer ${token}`, accept: "application/vnd.github+json" },
    });
    if (!res.ok) throw new Error(`REST ${res.status} on ${path}`);
    return res.json();
  }
  return JSON.parse(execFileSync("gh", ["api", path], { encoding: "utf8" }));
}

const data = await graphql();
const cc = data.user.contributionsCollection;
const cal = cc.contributionCalendar;
const days = cal.weeks.flatMap((w) => w.contributionDays);

let run = 0;
let streak = 0;
for (const d of days) {
  run = d.contributionCount > 0 ? run + 1 : 0;
  streak = Math.max(streak, run);
}
const busiest = days.reduce((a, b) => (b.contributionCount > a.contributionCount ? b : a));
const activeDays = days.filter((d) => d.contributionCount > 0).length;

const user = await rest(`users/${USER}`);

const out = `// GENERATED by scripts/refresh-stats.mjs — do not edit by hand.
// Source: GitHub GraphQL contributions API + REST user endpoint.
// Window: ${days[0].date} → ${days[days.length - 1].date}. Pulled ${to.toISOString().slice(0, 10)}.

export const statsWindow = {
  from: "${days[0].date}",
  to: "${days[days.length - 1].date}",
  pulledOn: "${to.toISOString().slice(0, 10)}",
} as const;

export const stats = {
  contributions: ${cal.totalContributions},
  publicCommits: ${cc.totalCommitContributions},
  privateContributions: ${cc.restrictedContributionsCount},
  pullRequests: ${cc.totalPullRequestContributions},
  reviews: ${cc.totalPullRequestReviewContributions},
  activeDays: ${activeDays},
  totalDays: ${days.length},
  peakStreak: ${streak},
  busiestDay: { date: "${busiest.date}", count: ${busiest.contributionCount} },
  publicRepos: ${user.public_repos},
  followers: ${user.followers},
  joined: "${user.created_at.slice(0, 7)}",
} as const;

/** One entry per ISO week of the window, oldest first. */
export const weeks: { firstDay: string; total: number }[] = ${JSON.stringify(
  cal.weeks.map((w) => ({
    firstDay: w.firstDay,
    total: w.contributionDays.reduce((s, d) => s + d.contributionCount, 0),
  })),
  null,
  2,
)};

/** Daily counts, column-major by week — the local heatmap fallback. */
export const calendar: { date: string; count: number }[][] = ${JSON.stringify(
  cal.weeks.map((w) => w.contributionDays.map((d) => ({ date: d.date, count: d.contributionCount }))),
)};
`;

writeFileSync(new URL("../src/data/github-stats.ts", import.meta.url), out);
console.log(
  `wrote src/data/github-stats.ts — ${cal.totalContributions} contributions, ` +
    `${activeDays}/${days.length} active days, ${streak}-day peak streak, ${user.public_repos} public repos`,
);
